// Generates src/element-map.d.ts: a typed map of every element id in src/template.html.
// Re-run (npm run gen:ids) whenever ids are added/renamed/retyped in the HTML.
import { JSDOM } from 'jsdom';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'src', 'template.html'), 'utf8');
const doc = new JSDOM(html).window.document;

const seen = new Map();
const dupes = [];
for (const el of doc.querySelectorAll('[id]')) {
  const type = el.constructor.name; // e.g. HTMLInputElement, HTMLDivElement, HTMLElement (for <i>)
  if (seen.has(el.id)) dupes.push(el.id);
  seen.set(el.id, type);
}
const ids = [...seen.keys()].sort((a, b) => a.localeCompare(b));
const body = ids.map((id) => `  ${/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id)}: ${seen.get(id)};`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-element-map.mjs from src/template.html - do not edit by hand.
// Maps every static element id in the page to its DOM element type.
interface ElementMap {
${body}
}
`;
writeFileSync(join(root, 'src', 'element-map.d.ts'), out);
console.log(`element-map.d.ts: ${ids.length} ids` + (dupes.length ? `; DUPLICATE ids: ${dupes.join(', ')}` : '; no duplicates'));

// Cross-check: every LITERAL id passed to byId()/byIdOrNull() must exist in the static HTML.
// (A typo'd literal would otherwise fall through to the generic `string` overload and only fail at run time.)
import { readdirSync } from 'node:fs';
const srcDir = join(root, 'src');
const sources = readdirSync(srcDir).filter((f) => /^\d.*\.ts$/.test(f));
const missing = [];
let literalCalls = 0;
for (const f of sources) {
  const code = readFileSync(join(srcDir, f), 'utf8');
  for (const m of code.matchAll(/\bbyId(?:OrNull)?\('([^']+)'\)/g)) {
    literalCalls++;
    if (!seen.has(m[1])) missing.push(`${f}: #${m[1]}`);
  }
}
console.log(`literal byId()/byIdOrNull() calls checked: ${literalCalls}; ids missing from template.html: ${missing.length ? '\n  ' + missing.join('\n  ') : 'none'}`);
if (missing.length) process.exit(1);
